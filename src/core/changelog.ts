/** Записи новее той, что пользователь уже видел (lastSeen = id последней просмотренной); без неё — пусто (первый запуск). */
export function unseen(lastSeen: string | null, list: Change[] = CHANGES): Change[] {
  if (lastSeen === null) return [];
  const i = list.findIndex((c) => c.id === lastSeen);
  return i === -1 ? list.slice(0, 1) : list.slice(0, i);
}
