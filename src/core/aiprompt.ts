/**
 * Готовые инструкции для ИИ (Claude, ChatGPT и др.): как собрать файл, который «Черта» точно примет.
 * Человек копирует инструкцию, добавляет свой материал (фото страницы учебника, список слов, текст) и вставляет ответ в импорт.
 */
export type AiKind = "cards" | "text" | "course";

const COMMON = `Ответ — только содержимое файла в одном блоке кода (\`\`\`), без пояснений до и после. Китайский — упрощённые иероглифы. Пиньинь — латиницей с цифрами тонов через пробел между слогами (xue2 xi2, нейтральный тон — 5: ma1 ma5). Переводы — на русском, коротко.`;

const CARDS = `Сделай список слов для карточек приложения «Черта».
Формат: одно слово в строке, три поля через « | »:
иероглифы | пиньинь | значение по-русски

Пример:
学习 | xue2 xi2 | учиться, изучать
老师 | lao3 shi1 | учитель
朋友 | peng2 you5 | друг

Можно разбить слова на несколько колод: перед каждой колодой строка «## Название колоды».
Слова не повторяются. Значение — 1–3 самых частых русских перевода через запятую или «;».
${COMMON}`;

const TEXT = `Сделай текст для чтения в приложении «Черта».
Формат:
=== уровень HSK (1–6) | Название текста
+ новое слово | пиньинь | значение      ← слова выше уровня текста, по строке
китайское предложение | перевод на русский      ← по одному предложению в строке
? вопрос по тексту на русском | вариант | верный вариант* | вариант      ← 2–3 вопроса, верный со звёздочкой

Пример:
=== 2 | Мой выходной
+ 公园 | gong1 yuan2 | парк
星期六我和朋友去公园。 | В субботу мы с другом пошли в парк.
天气很好，我们走了一个小时。 | Погода была хорошая, мы гуляли час.
? Куда они пошли? | В школу | В парк* | В магазин

В одном файле может быть несколько текстов — каждый начинается своей строкой «===».
Предложения короткие и законченные, слова — по возможности не выше указанного уровня HSK.
${COMMON}`;

const COURSE = `Сделай курс для раздела «Упражнения» приложения «Черта» — уроки по порядку, как в учебнике.
Каждая строка начинается со своего значка:
# Название курса
#level: 1                                 ← уровень HSK курса (1–6)
#about: Короткое описание курса
### Раздел                                 ← необязательно: тема для нескольких уроков
## Урок 1. Название урока                  ← начало урока
= Цель урока одной фразой                  ← необязательно
+ 你好 | ni3 hao3 | здравствуй             ← слово урока: иероглифы | пиньинь | значение (5–15 слов)
& Название правила грамматики              ← необязательно: правило
% Объяснение правила по-русски (можно несколько строк «%»)
%| форма | значение | пример                ← необязательно: строки таблицы (первая — заголовок)
%| 是 | быть | 我是学生
%! 我是高兴 — так нельзя, нужно 我很高兴      ← необязательно: частая ошибка
%> 是 не ставится перед прилагательным       ← необязательно: заметка
%e 我是学生。 | Я студент.                  ← пример к правилу
%x 我___学生。 | Я студент. | 是* | 有 | 在  ← задание: ___ на месте пропуска, перевод, варианты, верный со звёздочкой
你好！ | Привет!                           ← предложение урока: китайский | русский (6–10 штук)
@ Название диалога                         ← диалог: реплики сразу под этой строкой
A: 你好！ | Привет!
B: 你好！你叫什么名字？ | Привет! Как тебя зовут?
? Вопрос по диалогу | вариант | верный* | вариант   ← сразу под репликами, без пустой строки
(пустая строка заканчивает диалог)

Пример урока:
## Урок 1. Знакомство
= Поздороваться и назвать себя
+ 你好 | ni3 hao3 | здравствуй
+ 叫 | jiao4 | звать
+ 名字 | ming2 zi5 | имя
& 叫 + имя
% Имя называют глаголом 叫: 我叫… — «меня зовут…».
%e 我叫安娜。 | Меня зовут Анна.
%x 我___王明。 | Меня зовут Ван Мин. | 叫* | 是 | 有
你好！ | Привет!
你叫什么名字？ | Как тебя зовут?
我叫安娜。 | Меня зовут Анна.

@ Знакомство
A: 你好！我叫王明。 | Привет! Меня зовут Ван Мин.
B: 你好！我叫安娜。 | Привет! Меня зовут Анна.
? Как зовут B? | Ван Мин | Анна* | Ли Юэ

Правила:
— в предложениях, диалогах и заданиях урока только слова этого и прошлых уроков (и самые простые служебные слова);
— в заданиях %x и вопросах «?» ровно один верный вариант, остальные — явно неверные (не тоже правильные);
— объяснения и переводы — по-русски, свои, не копируй тексты учебника дословно.
${COMMON}`;

/** Инструкция для ИИ; wish — что нужно (тема, уровень, «по фото страницы учебника» и т. п.). */
export function aiPrompt(kind: AiKind, wish = ""): string {
  const base = kind === "cards" ? CARDS : kind === "text" ? TEXT : COURSE;
  const w = wish.trim();
  return `${base}\n\nЗадание: ${w || (kind === "cards" ? "слова из материала, который я приложу ниже (фото, список или текст)." : kind === "text" ? "текст на тему и уровень, которые я укажу, или по материалу, который приложу." : "курс по материалу, который я приложу ниже (фото страниц учебника, список слов или темы уроков).")}`;
}
