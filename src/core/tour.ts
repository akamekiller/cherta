/** Экскурсия по приложению при первом запуске: шаги (тексты зависят от языка приложения). */
import type { View } from "../ui/nav.ts";

export type Pose = "hello" | "think" | "happy" | "sad" | "sleep";
export type TourStep = { pose: Pose; title: string; text: string; go?: View; goLabel?: string };

export function tourSteps(lang: "zh" | "ja"): TourStep[] {
  const ja = lang === "ja";
  const chars = ja ? "кану и кандзи" : "иероглифы";
  return [
    { pose: "hello", title: "Привет! Это «Черта»",
      text: `Я панда-помощница. Здесь учат ${chars}: пишете пальцем или стилусом, а приложение проверяет каждую черту. Покажу главное — это минута.` },
    { pose: "think", title: "Слова: словарь", go: "words", goLabel: "Открыть «Слова»",
      text: ja
        ? "В «Словах» ищите любое слово: кандзи, кана, ромадзи или по-русски. В статье — значения, примеры, порядок черт и кнопка «+ В колоду»."
        : "В «Словах» ищите любое слово: по иероглифу, пиньиню или по-русски, можно даже нарисовать иероглиф. В статье — значения, примеры, порядок черт и кнопка «+ В колоду»." },
    { pose: "happy", title: "Колоды", go: "home", goLabel: "Открыть «Карточки»",
      text: "Колода — набор слов для заучивания. Готовые (HSK, JLPT, по темам) добавляются из каталога на экране «Карточки», свои — кнопкой «+ В колоду» или импортом." },
    { pose: "think", title: "Карточка",
      text: ja
        ? "Видите значение — пишете слово в клетке, затем вводите чтение каной. Приложение оценивает ответ и само решает, когда показать слово снова."
        : "Видите значение — пишете иероглиф в клетке, затем выбираете или вводите пиньинь. Приложение оценивает ответ и само решает, когда показать слово снова." },
    { pose: "happy", title: "Письмо",
      text: "Новое слово пишете по контуру, повторение — по памяти. Ошиблись три раза на черте — она подсветится. Перо (кисть, карандаш, ручка) и цвет чернил выбираются в настройках." },
    { pose: "sleep", title: "Тетрадь и курсы", go: "ex", goLabel: "Открыть «Упражнения»",
      text: "«Тетрадь прописей» — строки клеток, как на бумаге (можно распечатать). «Упражнения» — курсы по урокам: теория, слова, задания и диалоги. Это всё! Экскурсию можно повторить в Настройках." },
  ];
}

/** Подпись счётчика «2 из 6». */
export const stepLabel = (i: number, n: number) => `${i + 1} из ${n}`;
